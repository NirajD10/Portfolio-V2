/**
 * Runs on predev / prebuild (docs/plan/13 §1).
 * 1. Renders any missing placeholders.
 * 2. Resolves every slot: final file in public/ if present, otherwise its placeholder.
 * 3. Makes the 1024px WebGL texture for final images that need one.
 * 4. Points src/lib/clash.generated.ts at Clash Grotesk, or at the Geist fallback when the file is missing.
 * 5. Writes src/content/assets.generated.json.
 * 6. Copies detect-gpu's benchmark tables to public/gpu-benchmarks (self-hosted, no CDN request).
 * AVIF/WebP delivery is left to next/image (images.formats) — see DECISIONS.md.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { assetSlots, placeholderPath, placeholderTexturePath } from "../src/content/assets";
import type { ResolvedAsset } from "../src/lib/assets";
import { abs, finalTexturePath, findFinal, isMain, toUrl } from "./lib";
import { makePlaceholders } from "./make-placeholders";

function writeIfChanged(rel: string, content: string) {
  const file = abs(rel);
  if (existsSync(file) && readFileSync(file, "utf8") === content) return false;
  writeFileSync(file, content);
  return true;
}

async function texture(src: string, out: string) {
  if (existsSync(abs(out)) && statSync(abs(out)).mtimeMs >= statSync(abs(src)).mtimeMs) return;
  mkdirSync(path.dirname(abs(out)), { recursive: true });
  await sharp(abs(src)).resize(1024, 1024, { fit: "inside" }).webp({ quality: 82 }).toFile(abs(out));
}

const CLASH_FOUND = `// AUTO-GENERATED by scripts/assets-sync.ts — do not edit. Clash Grotesk found.
import localFont from "next/font/local";

export const clash = localFont({
  src: "../fonts/ClashGrotesk-Variable.woff2",
  variable: "--font-clash",
  weight: "200 700",
  display: "swap",
});
export const clashLoaded = true;
`;

const CLASH_MISSING = `// AUTO-GENERATED by scripts/assets-sync.ts — do not edit.
// src/fonts/ClashGrotesk-Variable.woff2 is missing: --font-clash stays unset and --font-display uses Geist.
export const clash = { variable: "", className: "" };
export const clashLoaded = false;
`;

export async function syncAssets() {
  const placeholders = await makePlaceholders();
  const out: Record<string, ResolvedAsset> = {};

  for (const slot of assetSlots) {
    const final = findFinal(slot);
    switch (slot.kind) {
      case "image": {
        if (final) {
          const meta = await sharp(abs(final)).metadata();
          let tex: string | undefined;
          if (slot.texture) {
            tex = finalTexturePath(slot);
            await texture(final, tex);
          }
          out[slot.id] = {
            kind: "image",
            src: toUrl(final),
            width: meta.width ?? slot.width!,
            height: meta.height ?? slot.height!,
            placeholder: false,
            ...(tex && { texture: toUrl(tex) }),
          };
        } else {
          out[slot.id] = {
            kind: "image",
            src: toUrl(placeholderPath(slot.id)),
            width: slot.width!,
            height: slot.height!,
            placeholder: true,
            ...(slot.texture && { texture: toUrl(placeholderTexturePath(slot.id)) }),
          };
        }
        break;
      }
      case "logo":
        out[slot.id] = {
          kind: "logo",
          src: final ? toUrl(final) : null,
          placeholder: !final,
          monogram: slot.monogram!,
        };
        break;
      case "file":
      case "sound":
        out[slot.id] = { kind: slot.kind, src: final ? toUrl(final) : null, placeholder: !final };
        break;
      case "font":
      case "reference":
        out[slot.id] = { kind: slot.kind, src: null, placeholder: !final };
        break;
    }
  }

  const fontChanged = writeIfChanged(
    "src/lib/clash.generated.ts",
    findFinal(assetSlots.find((s) => s.id === "font.clash")!) ? CLASH_FOUND : CLASH_MISSING,
  );
  const jsonChanged = writeIfChanged(
    "src/content/assets.generated.json",
    JSON.stringify(out, null, 2) + "\n",
  );
  const benchmarks = abs("node_modules/detect-gpu/dist/benchmarks");
  if (existsSync(benchmarks) && !existsSync(abs("public/gpu-benchmarks"))) {
    cpSync(benchmarks, abs("public/gpu-benchmarks"), { recursive: true });
  }

  const pending = Object.values(out).filter((a) => a.placeholder).length;

  console.log(
    `assets: ${Object.keys(out).length} slots, ${pending} on placeholder · placeholders rendered: ${placeholders.made}` +
      (jsonChanged ? " · manifest updated" : "") +
      (fontChanged ? " · font module updated" : ""),
  );
}

if (isMain(import.meta.url)) {
  syncAssets().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
